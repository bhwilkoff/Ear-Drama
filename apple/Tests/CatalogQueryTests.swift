    /// The served schema, from the builder itself, so the fixture cannot drift.
    static func servedDDL() throws -> String {
        let text = try String(contentsOf: repoRoot.appendingPathComponent("catalog/tools/build_projection.py"),
                              encoding: .utf8)
        func block(_ name: String) throws -> String {
            let start = try #require(text.range(of: "\(name) = \"\"\"")).upperBound
            let end = try #require(text.range(of: "\"\"\"", range: start..<text.endIndex)).lowerBound
            return String(text[start..<end])
        }
        return try block("SCHEMA") + block("INDEXES")
    }

    /// Builds a fixture database; `rightsLines` nil leaves the meta key out.
    static func make(rightsLines: [String: String]? = RightsDisplay.contract,
                     clearNoRecommend: Bool = false, dropLoudness: Bool = false,
                     dropTranscript: Bool = false, listenShelves: String? = nil, dropArt: Bool = false,
                     episodeRows: [Ep]? = nil,
                     seriesRows: [(key: String, name: String, genre: String?, first: String?, last: String?, networks: String?)]? = nil
    ) throws -> URL {
        let episodes = episodeRows ?? Self.episodes
        let series = seriesRows ?? Self.series
        let url = FileManager.default.temporaryDirectory.appendingPathComponent("fixture-\(UUID().uuidString).sqlite")
        var h: OpaquePointer?
        try #require(sqlite3_open(url.path, &h) == SQLITE_OK)
        defer { sqlite3_close(h) }
        func exec(_ sql: String) throws {
            var err: UnsafeMutablePointer<CChar>?
            let rc = sqlite3_exec(h, sql, nil, nil, &err)
            guard rc == SQLITE_OK else { throw FixtureError("\(err.map { String(cString: $0) } ?? "") in \(sql)") }
        }
        func insert(_ sql: String, _ values: [Any?]) throws {
            var stmt: OpaquePointer?
            guard sqlite3_prepare_v2(h, sql, -1, &stmt, nil) == SQLITE_OK else { throw FixtureError(sql) }
            defer { sqlite3_finalize(stmt) }
            for (i, v) in values.enumerated() {
                let n = Int32(i + 1)
                switch v {
                case let s as String: sqlite3_bind_text(stmt, n, s, -1, SQLITE_TRANSIENT_TEST)
                case let x as Int: sqlite3_bind_int64(stmt, n, Int64(x))
                case let d as Double: sqlite3_bind_double(stmt, n, d)
                default: sqlite3_bind_null(stmt, n)
                }
            }
            guard sqlite3_step(stmt) == SQLITE_DONE else { throw FixtureError(sql) }
        }
        try exec(servedDDL())
        try insert("INSERT INTO meta VALUES (?, ?)", ["schemaVersion", "1"])
        if let rightsLines {
            let json = String(data: try JSONEncoder().encode(rightsLines), encoding: .utf8)
            try insert("INSERT INTO meta VALUES (?, ?)", ["rightsLines", json])
        }
        if let listenShelves {
            try insert("INSERT INTO meta VALUES (?, ?)", ["listenShelves", listenShelves])
        }
        let counts = Dictionary(grouping: episodes, by: \.series).mapValues(\.count)
        for s in series {
            try insert("INSERT INTO series (key, name, genre, first_date, last_date, networks, episodes, sort_name) VALUES (?,?,?,?,?,?,?,?)",
                       [s.key, s.name, s.genre, s.first, s.last, s.networks, counts[s.key] ?? 0, Self.sortNames[s.key] ?? s.name.lowercased()])
        }
        for (pid, name) in people { try insert("INSERT INTO people (id, name) VALUES (?, ?)", [pid, name]) }
        for c in credits { try insert("INSERT INTO credits VALUES (?,?,?,?)", [c.0, c.1, c.2, c.3]) }
        for (rowid, e) in episodes.enumerated() {
            try insert("""
                INSERT INTO episodes (rowid, id, series_key, air_date, season, num, title, length_s, rights,
                    rights_basis, no_recommend, network) VALUES (?,?,?,?,?,?,?,?,?,?,?,?)
                """, [rowid + 1, e.id, e.series, e.date, e.season, e.num, e.title, 1770.0, e.rights, e.basis,
                      clearNoRecommend ? nil : e.noRecommend, e.network])
            let file = "https://archive.org/download/\(e.series)_box/\(e.id.replacingOccurrences(of: "|", with: "_")).mp3"
            try insert("INSERT INTO recordings (episode_id, rank, archive_id, url, kbps, length_s) VALUES (?,?,?,?,?,?)",
                       [e.id, 0, "\(e.series)_box", file, 64, 1770.0])
            let seriesName = series.first { $0.key == e.series }?.name ?? ""
            let names = credits.filter { $0.0 == e.id }.compactMap { c in people.first { $0.0 == c.1 }?.1 }
            try insert("INSERT INTO episodes_fts (rowid, title, series, people, transcript) VALUES (?,?,?,?,?)",
                       [rowid + 1, e.title ?? "", seriesName, names.joined(separator: " "), transcripts[e.id]])
        }
        // A second, lesser copy: an Armed Forces rebroadcast, incomplete.
        try insert("""
            INSERT INTO recordings (episode_id, rank, archive_id, url, kbps, length_s, variant, partial)
            VALUES (?,?,?,?,?,?,?,?)
            """, ["suspense|1943-05-25", 1, "afrs_box", "https://archive.org/download/afrs_box/sorry%20afrs.mp3",
                  32, 1500.0, "AFRS", 1])
        try insert("INSERT INTO episode_aliases VALUES (?, ?)", ["suspense|old-slug", "suspense|1943-05-25"])
        // One measured episode (contract §3.1); every other row is NULL, as unmeasured.
        try insert("UPDATE episodes SET loudness_i = ?, loudness_tp = ? WHERE id = ?",
                   [-15.0, -6.0, "suspense|1943-05-25"])
        // One transcript passed the gate and is shown; the other failed it
        // (searchable, never shown), and its URL is set here only as a control:
        // the gate column decides, not the URL's presence.
        try insert("UPDATE episodes SET has_transcript = 1, transcript_url = ? WHERE id = ?",
                   [transcriptURL, "suspense|1942-10-20"])
        try insert("UPDATE episodes SET has_transcript = 0, transcript_url = ? WHERE id = ?",
                   ["https://archive.org/download/suspense_box/sorry.autogenerated.txt", "suspense|1943-05-25"])
        // Portraits (contract §3.3a): Agnes Moorehead is Suspense's star and the
        // 1943 episode's; Orson Welles' portrait owes a CC credit.
        try exec("""
            INSERT INTO art VALUES (1, 'https://commons.wikimedia.org/wiki/Special:FilePath/Agnes_Moorehead.jpg',
                600, 800, 'pd_us', NULL, NULL, 'https://commons.wikimedia.org/wiki/File:Agnes_Moorehead.jpg',
                '0.3,0.1,0.4,0.3');
            INSERT INTO art VALUES (2, 'https://commons.wikimedia.org/wiki/Special:FilePath/Orson_Welles.jpg',
                NULL, NULL, 'cc_by', 'Alan Light', 'Alan Light, CC BY 2.0',
                'https://commons.wikimedia.org/wiki/File:Orson_Welles.jpg', NULL);
            UPDATE people SET portrait = 1 WHERE id = 'p1';
            UPDATE people SET portrait = 2 WHERE id = 'p3';
            UPDATE series SET star = 'p1' WHERE key = 'suspense';
            UPDATE episodes SET star = 'p1' WHERE id = 'suspense|1943-05-25';
            UPDATE episodes SET star = 'p3' WHERE id = 'suspense|1942-10-20';
            """)
        // Two story arcs of Suspense (contract §3.3), the first offering the second.
        try exec("""
            INSERT INTO arcs VALUES ('suspense|arc|a', 'suspense', 'The Burning Court', 2, 'titled-parts', 'suspense|arc|b');
            INSERT INTO arcs VALUES ('suspense|arc|b', 'suspense', 'Sorry, Wrong Number', 2, 'titled-parts', NULL);
            INSERT INTO arc_parts VALUES ('suspense|1942-06-17', 'suspense|arc|a', 1);
            INSERT INTO arc_parts VALUES ('suspense|1942-10-20', 'suspense|arc|a', 2);
            INSERT INTO arc_parts VALUES ('suspense|1943-05-25', 'suspense|arc|b', 1);
            INSERT INTO arc_parts VALUES ('suspense|lost', 'suspense|arc|b', 2);
            """)
        if dropArt {
            // An older catalog: no portraits, and no arcs.
            try exec("DROP TABLE art; ALTER TABLE people DROP COLUMN portrait; ALTER TABLE series DROP COLUMN star; "
                     + "ALTER TABLE episodes DROP COLUMN star; DROP TABLE arcs; DROP TABLE arc_parts;")
        }
        // One episode links a castable script (contract §3.1, Decision 068).
        try exec("UPDATE episodes SET script = 'grw-A1' WHERE id = 'suspense|1943-05-25';")
        if dropTranscript {
            try exec("ALTER TABLE episodes DROP COLUMN transcript_url; ALTER TABLE episodes DROP COLUMN script;")
        }
        if dropLoudness {
            try exec("ALTER TABLE episodes DROP COLUMN loudness_i; ALTER TABLE episodes DROP COLUMN loudness_tp;")
        }
        return url
    }

    static func open(rightsLines: [String: String]? = RightsDisplay.contract,
                     clearNoRecommend: Bool = false, dropLoudness: Bool = false,
                     dropTranscript: Bool = false, listenShelves: String? = nil,
                     dropArt: Bool = false) throws -> CatalogDatabase {
        let url = try make(rightsLines: rightsLines, clearNoRecommend: clearNoRecommend, dropLoudness: dropLoudness,
                           dropTranscript: dropTranscript, listenShelves: listenShelves, dropArt: dropArt)
        return try #require(CatalogDatabase(path: url.path))
    }
