"""How good are archive.org's automatic transcripts? Measured against human scripts.

    python3 tools/measure_transcripts.py            # every episode with both, cached
    python3 tools/measure_transcripts.py --report

Decision 058: transcripts appear on screen only above a measured quality gate.
archive.org writes `{stem}.autogenerated.txt` beside many MP3s. Where the
Generic Radio Workshop holds the episode's script (`.cache/grw/text/`), this
aligns the two word sequences (difflib, in order) and records:

  recall     share of the script's words the transcript reproduces in order
  precision  share of the transcript's words that align to the script

A broadcast departs from its script (ad-libs, cuts, the commercials, the
announcer), so a perfect transcript still scores below 1: the distribution, not
any one number, sets the gate. Transcripts are cached in .cache/transcripts/.
"""
import argparse
import difflib
import json
import os
import re
import sqlite3
import statistics
import sys
import time
import urllib.parse
import urllib.request

sys.path.insert(0, os.path.dirname(__file__))
import ia_lib as ia

CACHE_DIR = os.path.join(ia.CACHE, "transcripts")
RESULTS = os.path.join(ia.CACHE, "transcript_quality.json")
UA = "EarDrama/0.1 (+https://eardrama.org; transcript quality measurement)"
WORD = re.compile(r"[a-z0-9']+")


def words(text):
    return WORD.findall(text.lower().replace("’", "'"))


def align(script, transcript):
    sm = difflib.SequenceMatcher(None, script, transcript, autojunk=False)
    matched = sum(b.size for b in sm.get_matching_blocks())
    return matched / max(1, len(script)), matched / max(1, len(transcript))


def fetch_transcript(archive_id, file):
    stem = file.rsplit(".", 1)[0]
    path = os.path.join(CACHE_DIR, archive_id, stem + ".autogenerated.txt")
    if os.path.exists(path):
        return open(path, encoding="utf-8").read()
    url = "https://archive.org/download/{}/{}".format(urllib.parse.quote(archive_id, safe=""),
                                                      urllib.parse.quote(stem + ".autogenerated.txt", safe="/"))
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    try:
        text = urllib.request.urlopen(req, timeout=60).read().decode("utf-8", "replace")
    except urllib.error.HTTPError as e:
        if e.code in (404, 410):
            return None
        raise RuntimeError(f"HTTP {e.code}")
    except (urllib.error.URLError, TimeoutError) as e:
        raise RuntimeError(str(e)[:80])
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8").write(text)
    time.sleep(1)
    return text


def pairs(db):
    c = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    return c.execute("SELECT s.id, s.episode_id, e.series_key, r.archive_id, r.file FROM scripts s "
                     "JOIN episodes e ON e.id = s.episode_id "
                     "JOIN recordings r ON r.episode_id = e.id AND r.rank = 0 "
                     "WHERE r.has_transcript = 1 AND s.text_cached = 1 ORDER BY s.episode_id").fetchall()


def report(results):
    ok = [r for r in results.values() if "recall" in r]
    if not ok:
        return {"measured": 0}
    rec = sorted(r["recall"] for r in ok)
    pre = sorted(r["precision"] for r in ok)
    q = lambda xs, p: round(xs[min(len(xs) - 1, int(p * len(xs)))], 3)
    return {"measured": len(ok), "series": len({r["series"] for r in ok}),
            "missing_transcript": sum(1 for r in results.values() if r.get("missing")),
            "recall": {"p10": q(rec, .1), "p25": q(rec, .25), "median": q(rec, .5), "p75": q(rec, .75), "p90": q(rec, .9)},
            "precision": {"p10": q(pre, .1), "p25": q(pre, .25), "median": q(pre, .5), "p75": q(pre, .75)}}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=os.path.join(ia.OUT, "radio-catalog.sqlite"))
    ap.add_argument("--report", action="store_true")
    a = ap.parse_args()
    results = json.load(open(RESULTS)) if os.path.exists(RESULTS) else {}
    if not a.report:
        todo = [p for p in pairs(a.db) if p[1] not in results]
        print(f"{len(todo)} episodes with a transcript and a script", flush=True)
        for i, (sid, eid, sk, aid, file) in enumerate(todo, 1):
            spath = os.path.join(ia.CACHE, "grw", "text", sid + ".txt")
            if not os.path.exists(spath):
                continue
            try:
                t = fetch_transcript(aid, file)
            except RuntimeError as e:
                print(f"skip {eid}: {e} (retried next run)", flush=True)
                continue
            if t is None:
                results[eid] = {"series": sk, "missing": True}
            else:
                r, p = align(words(open(spath, encoding="utf-8", errors="replace").read()), words(t))
                results[eid] = {"series": sk, "script": sid, "recall": round(r, 4), "precision": round(p, 4)}
            if i % 20 == 0 or i == len(todo):
                ia.write_json(RESULTS, results)
                print(f"{i}/{len(todo)}", flush=True)
    rep = report(results)
    print(json.dumps(rep, indent=1))
    ia.write_json(RESULTS, results)
    if not a.report and not rep["measured"]:
        sys.exit(1)


if __name__ == "__main__":
    main()
