"""Fetch archive.org's automatic transcripts for served episodes, in batches (DECISIONS 058).

    python3 tools/fetch_transcripts.py --batch 1500 --cache C.json.gz --max-minutes 75 --summary S.json
    python3 tools/fetch_transcripts.py --seed-dir .cache/transcripts --cache C.json.gz   # offline, no network
    python3 tools/fetch_transcripts.py --report --cache C.json.gz
    python3 tools/fetch_transcripts.py --merge FRESH RUN --out OUT.json.gz   # additive merge
    python3 tools/fetch_transcripts.py --guard OLD NEW                       # refuse a shrunken cache

archive.org writes `{stem}.autogenerated.txt` beside many MP3s (the research
database marks those recordings `has_transcript`). For each served episode
whose default copy has one, in the order of a stable hash of the episode id,
this fetches the text once, runs the on-screen gate (transcript_gate.py) on it
with the copy's length, and stores the text with the gate's verdict and
features. The cache is keyed by episode id and records the URL it read: a new
default copy is fetched again, and the projection uses only an entry whose URL
is the current copy's (build_projection.py imports `text_for`).

Additive, like measure_loudness.py: a text is never replaced by a miss or an
error, only by a newer text. A 404 or 410 is recorded as `missing` and tried
again after --retry-days (archive.org derives transcripts over time); another
4xx is a recorded error; a 429, a 5xx, or a dropped connection is transient and
never recorded, so the next run tries it again. One request at a time, a pause
between requests, a back-off after a transient failure, and a streak breaker.
"""
import argparse
import calendar
import gzip
import hashlib
import http.client
import json
import os
import sqlite3
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

sys.path.insert(0, os.path.dirname(__file__))
import ia_lib as ia
import transcript_gate as G

UA = "EarDrama/0.1 (+https://eardrama.org)"
SUFFIX = ".autogenerated.txt"
SERVED = ("keep_clean", "keep_unclaimed")
BREAKER = 20          # consecutive failures stop a batch: the host is refusing us, not the files
SAVE_EVERY_S = 120


class Transient(Exception):
    pass


def stable(s):
    return int(hashlib.sha1(s.encode()).hexdigest()[:12], 16)


def now_iso(t=None):
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(t))


def transcript_url(archive_id, file):
    """The .txt beside a copy, percent-encoded as build_projection.download_url encodes audio."""
    stem = file.rsplit(".", 1)[0]
    return "https://archive.org/download/{}/{}".format(urllib.parse.quote(archive_id, safe=""),
                                                       urllib.parse.quote(stem + SUFFIX, safe="/"))


def has_text(r):
    return bool(r) and "text" in r


def text_for(r, url):
    """The cached text of THIS copy's transcript, or None: the projection's one predicate."""
    return r["text"] if has_text(r) and r.get("url") == url else None


def load(path):
    if not path or not os.path.exists(path):
        return {}
    with (gzip.open if path.endswith(".gz") else open)(path, "rt", encoding="utf-8") as f:
        return json.load(f)


def save(path, cache):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    tmp = path + ".tmp"
    if path.endswith(".gz"):
        with gzip.open(tmp, "wt", encoding="utf-8", compresslevel=6) as f:
            json.dump(cache, f, ensure_ascii=False)
    else:
        with open(tmp, "w", encoding="utf-8") as f:
            json.dump(cache, f, ensure_ascii=False)
    os.replace(tmp, path)


def entry(item, text):
    shown, f = G.shown(text, item["length_s"])
    return {"url": item["url"], "fetchedAt": now_iso(), "length_s": item["length_s"],
            "bytes": len(text.encode("utf-8")), "gate": {"shown": shown, **f}, "text": text}


def fetch(item, timeout=60):
    """One transcript. Returns a cache entry; raises Transient for anything worth retrying."""
    req = urllib.request.Request(item["url"], headers={"User-Agent": UA})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            body = resp.read()
    except urllib.error.HTTPError as e:
        if e.code in (404, 410):
            return {"url": item["url"], "fetchedAt": now_iso(), "missing": True, "status": e.code}
        if e.code == 429 or e.code >= 500:
            raise Transient(f"HTTP {e.code}", e.headers.get("Retry-After") if e.headers else None)
        return {"url": item["url"], "fetchedAt": now_iso(), "error": f"HTTP {e.code}"}
    except (urllib.error.URLError, TimeoutError, ConnectionError, http.client.HTTPException, OSError) as e:
        raise Transient(str(e)[:120], None)
    return entry(item, body.decode("utf-8", "replace"))


def attempted_at(r):
    return max([r.get("fetchedAt") or "", ((r.get("lastAttempt") or {}).get("at") or "")])


def merge_entry(old, new):
    """Additive: a text is never replaced by a miss or an error, only by a newer text."""
    if not old:
        return new
    if not new or new is old:
        return old
    newer = (new.get("fetchedAt") or "") >= (old.get("fetchedAt") or "")
    if not has_text(new):
        if has_text(old):
            if (new.get("fetchedAt") or "") > attempted_at(old):
                return {**old, "lastAttempt": {"url": new.get("url"), "at": new.get("fetchedAt"),
                                               "result": "missing" if new.get("missing") else new.get("error")}}
            return old
        return new if newer else old
    if not has_text(old):
        return new
    return new if newer else old


def merge(a, b):
    out = dict(a)
    for k, v in b.items():
        out[k] = merge_entry(out.get(k), v)
    return out


def tally(cache):
    texts = [r for r in cache.values() if has_text(r)]
    return {"entries": len(cache), "texts": len(texts),
            "shown": sum(1 for r in texts if (r.get("gate") or {}).get("shown")),
            "missing": sum(1 for r in cache.values() if r.get("missing")),
            "errors": sum(1 for r in cache.values() if "error" in r),
            "text_bytes": sum(r.get("bytes", 0) for r in texts)}


def guard(old, new):
    """Why `new` must not be published over `old` (empty list = it may)."""
    a, b = tally(old), tally(new)
    bad = [f"{k} {a[k]} -> {b[k]}" for k in ("entries", "texts") if b[k] < a[k]]
    lost = [k for k in old if k not in new]
    if lost:
        bad.append(f"{len(lost)} ids dropped (first: {lost[0]})")
    return bad


def candidates(db):
    """Every served episode whose default copy has a transcript, in stable-hash order."""
    c = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    q = ",".join("?" * len(SERVED))
    rows = c.execute("SELECT e.id, r.archive_id, r.file, r.length_s FROM episodes e "
                     "JOIN recordings r ON r.episode_id = e.id AND r.rank = 0 "
                     f"WHERE r.has_transcript = 1 AND e.state IN ({q})", SERVED).fetchall()
    c.close()
    return [{"id": eid, "url": transcript_url(aid, f), "length_s": length, "archive_id": aid, "file": f}
            for _, eid, aid, f, length in sorted((stable(r[0]), *r) for r in rows)]


def due(r, url, now, retry_days):
    if not r:
        return True
    if has_text(r) and r.get("url") == url:
        return False
    tried = [(r.get("url"), r.get("fetchedAt")),
             ((r.get("lastAttempt") or {}).get("url"), (r.get("lastAttempt") or {}).get("at"))]
    for u, at in tried:
        if u == url and at and now - calendar.timegm(time.strptime(at, "%Y-%m-%dT%H:%M:%SZ")) < retry_days * 86400:
            return False
    return True


def plan(cands, cache, n, retry_days, now=None):
    now = time.time() if now is None else now
    todo = [it for it in cands if due(cache.get(it["id"]), it["url"], now, retry_days)]
    return todo[:n], len(todo)


def run_batch(todo, cache, path, deadline, pace=1.0, fetch_fn=fetch, sleep=time.sleep):
    """Fetch `todo` one at a time, saving additively as it goes. Returns this run's counts."""
    got = {"texts": 0, "shown": 0, "missing": 0, "errors": 0, "transient": 0, "not_started": 0, "breaker": False}
    streak, last_save = 0, time.time()
    for i, item in enumerate(todo):
        if got["breaker"] or (deadline is not None and time.time() > deadline):
            got["not_started"] = len(todo) - i
            break
        try:
            r = fetch_fn(item)
        except Transient as e:
            got["transient"] += 1
            streak += 1
            if streak >= BREAKER:
                got["breaker"] = True
            retry_after = e.args[1] if len(e.args) > 1 else None
            wait = float(retry_after) if retry_after and str(retry_after).isdigit() else 5.0 * streak
            sleep(min(120.0, wait))
            continue
        if has_text(r):
            got["texts"] += 1
            got["shown"] += bool(r["gate"]["shown"])
            streak = 0
        elif r.get("missing"):
            got["missing"] += 1
            streak = 0
        else:
            got["errors"] += 1
            streak += 1
            if streak >= BREAKER:
                got["breaker"] = True
        cache[item["id"]] = merge_entry(cache.get(item["id"]), r)
        if time.time() - last_save > SAVE_EVERY_S:
            save(path, cache)
            last_save = time.time()
            print(f"{i + 1}/{len(todo)} {tally(cache)}", flush=True)
        sleep(pace)
    save(path, cache)
    return got


def verdict(todo, got):
    """idle: nothing was due. all_failed: something was due and nothing came back. fetched otherwise."""
    if not todo:
        return "idle"
    if got["texts"] + got["missing"] == 0:
        return "all_failed"
    return "fetched"


def seed(cands, cache, folder):
    """Fill the cache from a folder of already-fetched texts ({archive_id}/{stem}.autogenerated.txt), offline."""
    n = 0
    for it in cands:
        p = os.path.join(folder, it["archive_id"], it["file"].rsplit(".", 1)[0] + SUFFIX)
        if os.path.exists(p) and not has_text(cache.get(it["id"])):
            cache[it["id"]] = merge_entry(cache.get(it["id"]), entry(it, open(p, encoding="utf-8").read()))
            n += 1
    return n


def report(cache):
    texts = [r for r in cache.values() if has_text(r)]
    gz = sum(len(gzip.compress(r["text"].encode("utf-8"), 6)) for r in texts)
    sizes = sorted(r["bytes"] for r in texts)
    hidden = [{k: r["gate"][k] for k in ("words", "wpm", "repeat")} for r in texts if not r["gate"]["shown"]]
    return {**tally(cache), "text_gzip_bytes": gz,
            "bytes_median": sizes[len(sizes) // 2] if sizes else 0,
            "bytes_max": sizes[-1] if sizes else 0, "hidden": hidden[:20]}


def main():
    t_start = time.time()
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=os.path.join(ia.OUT, "radio-catalog.sqlite"),
                    help="the research database (recordings.has_transcript lives there)")
    ap.add_argument("--cache", default=os.path.join(ia.CACHE, "transcripts.json.gz"))
    ap.add_argument("--batch", type=int)
    ap.add_argument("--max-minutes", type=float, help="stop starting new fetches past this")
    ap.add_argument("--retry-days", type=float, default=30.0)
    ap.add_argument("--pace", type=float, default=1.0, help="seconds between requests")
    ap.add_argument("--summary")
    ap.add_argument("--seed-dir")
    ap.add_argument("--report", action="store_true")
    ap.add_argument("--merge", nargs=2, metavar=("FRESH", "RUN"))
    ap.add_argument("--out")
    ap.add_argument("--guard", nargs=2, metavar=("OLD", "NEW"))
    a = ap.parse_args()

    if a.guard:
        old, new = load(a.guard[0]), load(a.guard[1])
        bad = guard(old, new)
        print(f"guard: {tally(old)} -> {tally(new)}")
        if bad:
            raise SystemExit("refusing a shrunken transcript cache: " + "; ".join(bad))
        return
    if a.merge:
        if not a.out:
            raise SystemExit("--merge needs --out")
        fresh, run = load(a.merge[0]), load(a.merge[1])
        out = merge(fresh, run)
        save(a.out, out)
        print(f"merged: fresh {tally(fresh)} + run {tally(run)} -> {tally(out)}")
        return

    cache = load(a.cache)
    if a.report:
        print(json.dumps(report(cache), indent=1))
        return
    cands = candidates(a.db)
    if a.seed_dir:
        n = seed(cands, cache, a.seed_dir)
        save(a.cache, cache)
        print(f"seeded {n} of {len(cands)} candidates from {a.seed_dir}: {tally(cache)}")
        return
    if a.batch is None:
        raise SystemExit("--batch N, --seed-dir, --report, --merge, or --guard")
    deadline = t_start + a.max_minutes * 60 if a.max_minutes else None
    todo, due_n = plan(cands, cache, a.batch, a.retry_days)
    print(f"{len(cands)} served episodes with a transcript; {due_n} due; fetching {len(todo)}", flush=True)
    got = run_batch(todo, cache, a.cache, deadline, a.pace)
    covered = sum(1 for it in cands if text_for(cache.get(it["id"]), it["url"]) is not None)
    summary = {**got, "planned": len(todo), "due_after": due_n - got["texts"] - got["missing"] - got["errors"],
               "candidates": len(cands), "covered": covered, "cache": tally(cache), "verdict": verdict(todo, got),
               "minutes": round((time.time() - t_start) / 60, 1)}
    if a.summary:
        ia.write_json(a.summary, summary)
    print(f"[catalog-transcripts] fetched {got['texts']} texts ({got['shown']} shown), {got['missing']} missing, "
          f"{got['errors']} errors, {got['transient']} transient of {len(todo)} planned; {covered} of "
          f"{len(cands)} candidates cached; verdict {summary['verdict']}", flush=True)


if __name__ == "__main__":
    main()
