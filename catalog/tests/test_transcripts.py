# --- fetch: a real HTTP exchange, classified -------------------------------------
STATUS = {}


class H(http.server.BaseHTTPRequestHandler):
    def do_GET(self):
        code = STATUS.get(self.path, 404)
        self.send_response(code)
        self.end_headers()
        if code == 200:
            self.wfile.write(GOOD.encode())
        STATUS.setdefault("ua", self.headers.get("User-Agent"))

    def log_message(self, *a):
        pass


srv = http.server.ThreadingHTTPServer(("127.0.0.1", 0), H)
threading.Thread(target=srv.serve_forever, daemon=True).start()
base = f"http://127.0.0.1:{srv.server_address[1]}"
STATUS.update({"/ok.txt": 200, "/busy.txt": 503, "/slow.txt": 429, "/gone.txt": 404, "/no.txt": 403})


def outcome(path):
    try:
        r = T.fetch({"id": "x", "url": base + path, "length_s": 1740.0}, timeout=5)
    except T.Transient:
        return "transient"
    return "text" if T.has_text(r) else ("missing" if r.get("missing") else r.get("error"))


check("fetch: a 200 is a text with the gate's verdict", outcome("/ok.txt"), "text")
check("fetch: a 503 is transient", outcome("/busy.txt"), "transient")
check("fetch: a 429 is transient", outcome("/slow.txt"), "transient")
check("fetch: a 404 is missing", outcome("/gone.txt"), "missing")
check("fetch: a 403 is a recorded error", outcome("/no.txt"), "HTTP 403")
check("fetch: an honest User-Agent", STATUS.get("ua"), "EarDrama/0.1 (+https://eardrama.org)")
r = T.fetch({"id": "x", "url": base + "/ok.txt", "length_s": 1740.0}, timeout=5)
check("fetch: verdict and features stored beside the text", (r["gate"]["shown"], sorted(r["gate"])),
      (True, ["repeat", "shown", "words", "wpm"]))
srv.shutdown()
srv.server_close()
check("control: a refused connection is transient", outcome("/ok.txt"), "transient")


# --- the batch: transient never cached, missing waits its window -----------------
def fake(values):
    def f(it):
        v = values.get(it["id"], "text")
        if v == "transient":
            raise T.Transient("HTTP 503", None)
        if v == "missing":
            return {"url": it["url"], "fetchedAt": T.now_iso(), "missing": True, "status": 404}
        return T.entry(it, GOOD)
    return f


